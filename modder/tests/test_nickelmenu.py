from pathlib import Path

import pytest

from modder.cli import main
from modder.exit_codes import PHASE_ERROR, SUCCESS
from modder.nickelmenu import PRESETS, Preset, render_files
from modder.userconfig import config_path, load_config, save_config

LEGACY = {
    ".adds/nm/qconf": "menu_item:main:Telnet:cmd_spawn:x\n",
    ".adds/nm/kfmon": "generator:main:kfmon\n",
    ".adds/nm/doc": "# NickelMenu doc\n",
    ".adds/nm/.icon-aum.png": "png",
    ".adds/nm/.icon-coffee.png": "png",
    ".adds/koreader/koreader.sh": "#!/bin/sh\n",
}


def _wizard(mount: Path, *extra: str) -> int:
    return main(["wizard", "nickelmenu", "--mount", str(mount), *extra])


def _nm(mount: Path) -> dict[str, str]:
    return {p.name: p.read_text() for p in (mount / ".adds/nm").iterdir()}


def test_presets_use_valid_nickelmenu_syntax() -> None:
    for preset in PRESETS:
        for line in preset.lines:
            directive = line.split(":", 1)[0]
            assert directive in {
                "menu_item",
                "chain_success",
                "chain_failure",
                "chain_always",
                "experimental",
                "generator",
            }, line


def test_labels_have_no_colon() -> None:
    for preset in PRESETS:
        for line in preset.lines:
            if line.startswith("menu_item:"):
                label = line.split(":")[2]
                assert label.strip(), line


def test_render_groups_into_one_file_per_group() -> None:
    chosen = [p for p in PRESETS if p.id in {"power.power", "display.dark_mode"}]
    files = render_files(chosen, owner="")
    assert set(files) == {
        Path(".adds/nm/kobo_manager_power"),
        Path(".adds/nm/kobo_manager_display"),
    }
    power = files[Path(".adds/nm/kobo_manager_power")]
    assert power.startswith("# Generated by kobo_manager")
    assert "menu_item:main:Reboot:power:reboot" in power


def test_owner_placeholder_is_filled() -> None:
    owner = next(p for p in PRESETS if p.id == "debug.owner")
    files = render_files([owner], owner="Jane Doe")
    assert "menu_item:main:Device Owner:dbg_msg:Jane Doe" in "".join(files.values())


def test_wizard_needs_restored_phase(tmp_path: Path, make_kobo) -> None:
    mount = make_kobo(tmp_path, files=LEGACY)
    assert _wizard(mount, "--non-interactive") == PHASE_ERROR
    assert "kobo_manager_power" not in _nm(mount)


def test_wizard_non_interactive_defaults(tmp_path: Path, make_kobo, restored) -> None:
    mount = make_kobo(tmp_path, files=LEGACY)
    assert _wizard(mount, "--non-interactive") == SUCCESS
    nm = _nm(mount)
    # legacy files moved out, doc and icons untouched
    assert "qconf" not in nm and "kfmon" not in nm
    assert "doc" in nm and ".icon-coffee.png" in nm
    disabled = mount / ".adds/kobo_manager/nm-disabled"
    assert (disabled / "qconf").read_text().startswith("menu_item:main:Telnet")
    # launchers via cmd_spawn, only for installed apps (KOReader yes, Plato no)
    launchers = nm["kobo_manager_launchers"]
    assert "exec /mnt/onboard/.adds/koreader/koreader.sh" in launchers
    assert "plato" not in launchers.lower()
    assert "generator:main:kfmon" not in "".join(nm.values())
    # review decisions
    footer = nm["kobo_manager_footer"]
    assert (
        "menu_main_15505_icon_active:/mnt/onboard/.adds/nm/.icon-coffee.png" in footer
    )
    assert "nickel_setting:toggle:invert" not in "".join(nm.values())
    assert "Telnet" not in "".join(nm.values())
    assert "library:gdrive" in nm["kobo_manager_library"]
    assert "library:instapaper" not in "".join(nm.values())
    assert "Free Memory" in nm["kobo_manager_debug"]
    assert "Device Owner" not in nm["kobo_manager_debug"]  # no owner configured


def test_wizard_uses_owner_and_overrides_from_config(
    tmp_path: Path, make_kobo, restored
) -> None:
    save_config(
        {"nickelmenu": {"owner": "Jane Doe", "enabled": ["network.auto_usb"]}},
        config_path(),
    )
    mount = make_kobo(tmp_path, files=LEGACY)
    assert _wizard(mount, "--non-interactive") == SUCCESS
    nm = _nm(mount)
    assert "dbg_msg:Jane Doe" in nm["kobo_manager_debug"]
    assert "auto_usb_gadget" in nm["kobo_manager_network"]


def test_wizard_dry_run_writes_nothing(tmp_path: Path, make_kobo, restored) -> None:
    mount = make_kobo(tmp_path, files=LEGACY)
    before = _nm(mount)
    assert _wizard(mount, "--non-interactive", "--dry-run") == SUCCESS
    assert _nm(mount) == before


def test_wizard_interactive_answers_are_saved(
    tmp_path: Path, make_kobo, restored, monkeypatch: pytest.MonkeyPatch
) -> None:
    mount = make_kobo(tmp_path, files=LEGACY)
    # owner prompt first, then "n" for every preset and every legacy file
    answers = iter(["Jane Doe"])
    monkeypatch.setattr("builtins.input", lambda _prompt="": next(answers, "n"))
    assert _wizard(mount) == SUCCESS
    nm = _nm(mount)
    assert "qconf" in nm  # legacy kept: we answered "n"
    assert [n for n in nm if n.startswith("kobo_manager_")] == ["kobo_manager_debug"]
    saved = load_config(config_path())["nickelmenu"]
    assert saved["owner"] == "Jane Doe"
    assert saved["enabled"] == ["debug.owner"]


def test_preset_ids_are_unique() -> None:
    ids = [p.id for p in PRESETS]
    assert len(ids) == len(set(ids))
    assert all(isinstance(p, Preset) for p in PRESETS)
