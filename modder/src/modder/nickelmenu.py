class Preset(NamedTuple):
    group: str
    key: str
    title: str
    lines: tuple[str, ...]
    default: bool = True
    requires: str = ""  # mod key that must be installed (catalogue)

    @property
    def id(self) -> str:
        return f"{self.group}.{self.key}"


