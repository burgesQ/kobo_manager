OWNER_ID = "debug.owner"
Ask = Callable[[str, bool], bool]


def available(installed: set[str]) -> list[Preset]:
    """Presets whose required mod is installed (owner handled separately)."""
    return [
        p
        for p in PRESETS
        if p.id != OWNER_ID and (not p.requires or p.requires in installed)
    ]


def choose(
    presets: Iterable[Preset],
    enabled: set[str],
    disabled: set[str],
    ask: Ask | None,
) -> list[Preset]:
    """Resolve each preset: config override > answer > preset default."""
    chosen: list[Preset] = []
    for preset in presets:
        default = preset.id in enabled or (preset.default and preset.id not in disabled)
        wanted = ask(f"{preset.id}: {preset.title}", default) if ask else default
        if wanted:
            chosen.append(preset)
    return chosen


def render_files(chosen: Iterable[Preset], owner: str) -> dict[Path, str]:
    groups: dict[str, list[str]] = {}
    for preset in chosen:
        body = groups.setdefault(preset.group, [])
        body.append(f"\n# {preset.title}")
        body.extend(line.replace("{owner}", owner) for line in preset.lines)
    return {
        NM_DIR / f"{GENERATED_PREFIX}{group}": HEADER + "\n".join(lines) + "\n"
        for group, lines in groups.items()
    }


def legacy_files(mount: Path) -> list[str]:
    """User files in ``.adds/nm`` that the generated config replaces."""
    nm = mount / NM_DIR
    if not nm.is_dir():
        return []
    return sorted(
        p.name
        for p in nm.iterdir()
        if p.is_file()
        and not p.name.startswith((".", GENERATED_PREFIX))
        and p.name not in NOT_LEGACY
    )


def plan(
    mount: Path,
    chosen: list[Preset],
    owner: str,
    migrate: Iterable[str],
) -> list[Op]:
    """Ops: drop stale generated files, write new ones, move legacy files out."""
    files = render_files(chosen, owner)
    ops: list[Op] = []
    nm = mount / NM_DIR
    if nm.is_dir():
        for stale in sorted(nm.glob(f"{GENERATED_PREFIX}*")):
            rel = NM_DIR / stale.name
            if rel not in files:
                ops.append(Move(rel, DISABLED_DIR / stale.name))
    ops.extend(WriteText(rel, content) for rel, content in sorted(files.items()))
    ops.extend(Move(NM_DIR / name, DISABLED_DIR / name) for name in migrate)
    return ops


def missing_icons(mount: Path, chosen: Iterable[Preset]) -> list[str]:
    text = "\n".join(line for p in chosen for line in p.lines)
    return [
        icon for icon in ICONS if icon in text and not (mount / NM_DIR / icon).exists()
    ]
